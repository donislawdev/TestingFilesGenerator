// What a preset ejects is bytes somebody else's manifest remembers.
//
// The manifest carries a recipe_hash, computed from the source a run consumed,
// and a preset's source is what eject prints - the same bytes, which is the
// whole of PR5. So a tidy-up that moved a space would tell everyone holding a
// record from an earlier run that their recipe had changed, and nothing in this
// tree would have said a word.
//
// PRESET-FEASIBILITY-2026-09-08.md section 5 asked for a measured gate on
// exactly one refactor: pulling the set a declared limit produces out of
// size-boundaries so that upload-validation could use it too. The measurement
// was taken by hand on 2026-09-08 and again either side of that move on
// 2026-09-22, both times 1298 B and this sum. This is that measurement kept.
//
// Every preset since 2026-09-24, and a refusal's words as well as a source's
// bytes. Until then only size-boundaries was pinned, and the change that day
// was to how the other four work their sets out: asking the format for its
// smallest size once rather than for every file, and planning a file the set
// holds twelve times once (docs/GUI-MEMORY-2026-09-23.md section 4j). Neither
// may move a byte, so the gate came first and was measured on the tree before
// the change. The cases are the ones that reach what changed - other formats
// in allow, which ask for other floors, a limit small enough that a refusal
// names the floor, and a spread narrow enough to reach it.
//
// What to do when it goes red: decide, rather than update. The sum moving is a
// breaking change under D11 - a major, a Breaking entry in the changelog, and
// the owner's decision, because untouchable rule 12 says the assistant does not
// raise the version. A refactor that moved it is a refactor to undo.
//
// Decided once, on 2026-09-25: every sum here moved, because an ejected recipe
// now says what each target is for (the purpose key, which PR5 puts in the
// recipe rather than beside it). The owner's call was a Changed entry and no
// major - D11 is about the bytes of the files, and not one of them moved,
// which the guards on generated bytes hold. What did move is the recipe_hash
// of every run from a preset. docs/PRESET-INSTRUCTIONS-2026-09-25.md section 6.
func TestEjectingAPresetGivesTheBytesItAlwaysGave(t *testing.T) {
	// bytes and sum are the whole document, refused the whole refusal. The
	// first row was measured 2026-09-08, the rest on 2026-09-24 before the
	// change they guard, and every sum again on 2026-09-25 when the purposes
	// arrived - see above.
	pinned := []struct {
		id      string
		args    preset.Args
		bytes   int
		sum     string
		refused string
	}{
		{id: "size-boundaries", args: preset.Args{"format": "pdf", "limit": "10mb"}, bytes: 2629, sum: "f0307b6325a227364fdcb81620d5029b1491447f7cc055aa99e06aa51aa33f54"},
		{id: "size-boundaries", args: preset.Args{"format": "png", "limit": "1mb"}, refused: "the preset size-boundaries cannot build this set - under_1mb would be 0 B, and a file cannot be smaller than nothing. Raise the limit above 1048650 B, narrow the spread, or choose a format with a smaller minimum. The limit asked for was 1048576 B."},
		{id: "size-boundaries", args: preset.Args{"format": "jpg", "limit": "10mb"}, bytes: 2489, sum: "6b8cd2e300de5f670a5c702e0145ef69d9965b9d43ed283943fbc3218efa8111"},
		{id: "size-boundaries", args: preset.Args{"format": "jpg", "limit": "2kb", "spread": "1kb"}, bytes: 1182, sum: "cbbb4f47bd0eca3846cf2c4f2f599a0c801287e361722798ce565ae3dd6c4b45"},
		{id: "size-boundaries", args: preset.Args{"format": "jpg", "limit": "300", "spread": "100"}, refused: "the preset size-boundaries cannot build this set - under_100 would be 200 B and the smallest JPG this build makes is 602 B. Raise the limit above 702 B, narrow the spread, or choose a format with a smaller minimum. The limit asked for was 300 B."},
		// Every upload-validation row moved on 2026-11-10: the set gained four
		// files sent under a name that leaves the upload directory, which is
		// four targets more in the recipe (docs/SEND-AS-2026-11-10.md). The
		// same shape as 2026-10-06, a Changed entry and no major: measured on
		// the default set against the tree before, each of the 71 files it
		// wrote keeps its bytes, its hash and its id, because the four stand
		// last in the run. What moves is the recipe_hash of a run from the
		// preset.
		{id: "upload-validation", args: preset.Args{}, bytes: 10463, sum: "c1594b58f57784e77e2e3359cb735965e83b2b2af612dc10e0f916a9a4876df8"},
		{id: "upload-validation", args: preset.Args{"limit": "5mb"}, bytes: 10451, sum: "34f0848ade008a9cc150d39389980827b5cca8aa850619ca3321346ae7e412c8"},
		{id: "upload-validation", args: preset.Args{"limit": "3kb"}, refused: "the preset upload-validation cannot build this set - allowed_pdf would be 1536 B and the smallest PDF this build makes is 3415 B. Raise the limit to 6830 B or more, or take pdf out of the allowed types. The limit asked for was 3072 B."},
		{id: "upload-validation", args: preset.Args{"allow": "docx,gif"}, bytes: 9877, sum: "610fe420a1a73b24c8d3cadbde4999b62b3c5282f253e6fb39dc1e83ab8db7b2"},
		{id: "upload-validation", args: preset.Args{"allow": "xlsx,ico,wav"}, bytes: 10497, sum: "6f310fa1b8e34c0a2df340288bc57eab1b4c765ceae6e4a8fd4c382cb9281de1"},
		{id: "upload-validation", args: preset.Args{"bulk": "3", "far-over": "off"}, bytes: 10101, sum: "f10b91008524cb38f4418eeb8995fdbf079061fc35c0d0df010dbd79db1fef33"},
		{id: "upload-validation", args: preset.Args{"deny": "exe,js"}, bytes: 9865, sum: "117deec7114242a7716ac965b8ea82f966769204d4731f06715474992db9f2e9"},
		{id: "tabular-import", args: preset.Args{}, bytes: 6045, sum: "e3d5ef9cc2633d05654b4bee16d62b61a30a776ff7a38cbdf35b3b073e18972e"},
		{id: "tabular-import", args: preset.Args{"rows": "100"}, bytes: 6042, sum: "7187e6a619e46a6f376361af433a45f9f4035c06f185c3cce7836179a3d4c2c0"},
		{id: "tabular-import", args: preset.Args{"columns": "5"}, bytes: 6042, sum: "81b712fe1186372ffdbf0d7c92ca753e5fac0f9083bb101695c4f0d37d8d4644"},
		{id: "text-encoding", args: preset.Args{}, bytes: 9263, sum: "322c2e02b446b0280555728f8401156d1569cd3046e57dc3af54bc0a2fde28aa"},
		{id: "text-encoding", args: preset.Args{"sample": "8kb"}, bytes: 9263, sum: "897a487c6d9eebaa1ff7d9bae44f17aec4bfcbd30597586f0b7b22eadb473ecd"},
		// Moved on 2026-10-06, decided by the owner the way 2026-09-25 was: the
		// set walks the whole registry, so the first film format is a target
		// more in it. A Changed entry and no major - not one generated byte
		// moved. Every format added later moves this row the same way.
		// Moved again the same day, before any release carried the film: its
		// picture began to change, and the smallest film the recipe asks for
		// went from 3044 B to 3294 B (docs/WIDEO-2026-10-06.md section 15).
		// The same Changed entry covers it.
		// Moved a third time on 2026-10-07, still before any release carried
		// the film, under the same decision: films are cut into tiles, and
		// planning counts a frame's tile_info as this package writes it rather
		// than at the longest gav1d could, so the smallest film went from
		// 3294 B to 3284 B - the same film, a bound ten bytes closer to it
		// (docs/WEBM-WYDAJNOSC-2026-10-06.md section 10).
		// Moved a fourth time on 2026-10-07, the owner's decision of the day
		// (docs/MP4-2026-10-07.md section 10): MP4 is a format more, so the
		// set has its smallest film, 3312 B. A Changed entry and no major -
		// no file any release made changes.
		// Moved a fifth time on 2026-10-07, under the same decision: geojson is
		// a format more, so the set has its smallest collection, 875 B
		// (docs/GEOJSON-2026-10-07.md).
		// Moved a sixth time on 2026-10-07, under the same decision: eml is a
		// format more, so the set has its smallest message, 289 B
		// (docs/EML-2026-10-07.md).
		// Moved a seventh time on 2026-10-15, by the owner's decision of that
		// day to change bytes: the smallest html page went from 118 B to 122 B
		// when its empty title became Page (O277, docs/HTML-6-2026-10-15.md).
		// The recipe keeps its length, only the number in it moves.
		// Moved an eighth time on 2026-10-15, under the decision of 2026-10-06:
		// rtf is a format more, so the set has its smallest document, 65 B - one
		// target, minimal_rtf, and nothing else in the recipe moves
		// (docs/RTF-2026-10-15.md).
		// Moved a ninth time on 2026-11-11, under the decision of 2026-10-06 and
		// said to the owner before the code this time: otlp is a format more, so
		// the set has its smallest file of spans, 1266 B - one target,
		// minimal_otlp, which stands after mp4, so the files after it in the run
		// take the next id (docs/OTLP-2026-11-10.md section 7).
		{id: "empty-and-minimal", args: preset.Args{}, bytes: 10821, sum: "8ca10156851379fae52dbf52fc220fd7470d0656b2f2e4ebc5f18af2a90dc7c2"},
		{id: "empty-and-minimal", args: preset.Args{"formats": "jpg,png,txt"}, bytes: 1472, sum: "19b12800372395ad3bf5cba6407ca654d7ed51eba3a5bc5436f76a94bc09253c"},
		// The preset of unusual file names, measured 2026-09-25 on its first
		// build: the default, and a format whose extension is a byte longer,
		// since the names about length are made to a length with it.
		{id: "filename-handling", args: preset.Args{}, bytes: 18983, sum: "f720c4a54c5fc17fea553a084fd13aaff4150c2fce5a4d953b10aee137ebe021"},
		{id: "filename-handling", args: preset.Args{"format": "docx"}, bytes: 19077, sum: "94a40d97bf549cbdd3e7ccaafe3372d7962ad542f358d37a2d945445c95d6f43"},
	}

	for _, want := range pinned {
		expanded, err := preset.Expand(want.id, want.args)
		if want.refused != "" {
			if err == nil || err.Error() != want.refused {
				t.Errorf("%s at %v was refused with\n  %q\nuntil now, and now gives\n  %v", want.id, want.args, want.refused, err)
			}
			continue
		}
		if err != nil {
			t.Errorf("%s refused %v: %v", want.id, want.args, err)
			continue
		}
		sum := sha256.Sum256(expanded.Source)
		got := hex.EncodeToString(sum[:])
		if len(expanded.Source) == want.bytes && got == want.sum {
			continue
		}
		t.Errorf("ejecting %s at %v gives %d B and %s, and it has given %d B and %s until now.\n"+
			"Every manifest written from this preset carries a hash of these bytes, so this is a "+
			"breaking change under D11 rather than a number to update here.\n%s",
			want.id, want.args, len(expanded.Source), got, want.bytes, want.sum, expanded.Source)
	}
}
