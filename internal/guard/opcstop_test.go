package guard

import (
	"context"
	"errors"
	"io"
	"sync/atomic"
	"testing"
	"time"

	"github.com/donislawdev/TestingFilesGenerator/internal/format"
)

// An Office package stops while it checksums its padding, not after it -
// docs/STABILITY-REVIEW-2026-10-26.md, R09.
//
// The padding part is stored, and its checksum has to be in the header before
// the part is written, so the padding is generated twice: once into a hash and
// once into the file. Until 2026-10-27 the first pass ran under a context of
// its own, so a stop that arrived during it waited for the whole padding to be
// hashed. Measured that day with a real Ctrl+Break on a 2 GB docx: 0.44 to 0.50
// s after the signal, where a txt of the same size ended in 0.02 s. At the
// zip32 ceiling of 4 GiB it is about twice that.
//
// The stop is placed by count rather than by clock. stopAfter answers "not
// stopped" to its first n questions and "stopped" to every one after, and the
// guard walks n upwards, so one of them lands inside the checksum pass whatever
// the number of parts in front of it - a number this guard does not have to
// know. A pass that does not ask cannot be stopped there, and hashes four
// gigabytes before the next question.
//
// Only the time is read, and the gap it has to see is three orders of
// magnitude: the first probe of a stopped pass is a 32 KiB chunk, the pass that
// ignores the stop is 4 GiB of generated bytes. docx stands for the three, as
// they reach the padding through one function in internal/format/opc.
func TestAnOfficePackageStopsWhileItChecksumsItsPadding(t *testing.T) {
	desc, err := format.Get("docx")
	if err != nil {
		t.Fatal(err)
	}
	// Just under the zip32 ceiling, so the padding is as large as a package
	// can carry and the pass that ignores the stop is as long as it can be.
	const size = 4<<30 - 1<<20
	plan, err := format.PlanWith(context.Background(), desc.Generator, format.Request{Bytes: size, Seed: 1, Label: true})
	if err != nil {
		t.Fatalf("planning a %d B docx: %v", size, err)
	}

	stoppedSomewhere := false
	for n := int64(0); n <= 64; n++ {
		ctx := &stopAfter{Context: context.Background(), after: n}
		started := time.Now()
		err := desc.Generator.Write(ctx, io.Discard, plan)
		took := time.Since(started)

		// The state the measurement depends on: the stop really happened.
		// Every n here is far below the questions a whole package asks, so a
		// write that ends without the stop has written four gigabytes and
		// says nothing about where the stop would have landed.
		if !errors.Is(err, context.Canceled) {
			t.Fatalf("with the stop after %d questions the write ended with %v rather than the stop", n, err)
		}
		stoppedSomewhere = true
		if took > stopGrace {
			t.Fatalf("with the stop after %d questions the write took %v to end - the padding was checksummed without looking at the stop", n, took)
		}
	}
	if !stoppedSomewhere {
		t.Fatal("no write was stopped, so nothing was measured")
	}
}

// stopGrace is how long a stopped write may take to end. Measured on
// 2026-10-27 on this machine: the 65 stopped writes of this guard took 0.06 s
// together, and the first write whose pass ignored the stop took 3.46 s. The
// line sits more than two hundred times away from each.
const stopGrace = 250 * time.Millisecond

// stopAfter is a context that is live for its first after questions and
// stopped for every one after.
type stopAfter struct {
	context.Context
	after int64
	asked atomic.Int64
}

func (c *stopAfter) Done() <-chan struct{} {
	if c.asked.Add(1) > c.after {
		return closedDone
	}
	return nil
}

func (c *stopAfter) Err() error {
	if c.asked.Load() > c.after {
		return context.Canceled
	}
	return nil
}

var closedDone = func() chan struct{} {
	ch := make(chan struct{})
	close(ch)
	return ch
}()
